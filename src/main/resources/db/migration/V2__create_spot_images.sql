CREATE TABLE spot_images (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guid UUID NOT NULL DEFAULT gen_random_uuid(),
    spot_id INTEGER NOT NULL,
    object_key VARCHAR(255) NOT NULL,
    content_type VARCHAR(100) NOT NULL,
    size BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_spot_images_guid UNIQUE (guid),
    CONSTRAINT uq_spot_images_object_key UNIQUE (object_key),

    CONSTRAINT fk_spot_images_spot
        FOREIGN KEY (spot_id) REFERENCES spots(id),

    CONSTRAINT ck_spot_images_size
        CHECK (size > 0)
);

CREATE INDEX ix_spot_images_spot_id_created_at
    ON spot_images(spot_id, created_at);