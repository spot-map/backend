CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE types (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    code VARCHAR(30) NOT NULL
);

CREATE TABLE users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100),
    avatar_url VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE auth_providers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER,
    provider VARCHAR(20),
    provider_user_id VARCHAR(100),
    email VARCHAR(100),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_auth_providers_user
        FOREIGN KEY (user_id) REFERENCES users(id),

    CONSTRAINT uq_auth_providers_provider_user
        UNIQUE (provider, provider_user_id)
);

CREATE TABLE spots (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guid UUID NOT NULL DEFAULT gen_random_uuid(),
    title VARCHAR(50) NOT NULL,
    description VARCHAR(100) NOT NULL,
    type_id INTEGER NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    lat NUMERIC(9, 6) NOT NULL,
    lng NUMERIC(9, 6) NOT NULL,

    location GEOGRAPHY(POINT, 4326)
        GENERATED ALWAYS AS (
            ST_SetSRID(ST_MakePoint(lng, lat), 4326)::geography
        ) STORED,

    CONSTRAINT uq_spots_guid UNIQUE (guid),

    CONSTRAINT fk_spots_type
        FOREIGN KEY (type_id) REFERENCES types(id)
);

CREATE INDEX ix_spots_created_at ON spots(created_at);
CREATE INDEX ix_spots_deleted ON spots(deleted);
CREATE INDEX ix_spots_type_id ON spots(type_id);
CREATE INDEX ix_spots_title ON spots(title);
CREATE INDEX ix_spots_lat_lng ON spots(lat, lng);
CREATE INDEX ix_spots_location ON spots USING GIST(location);

CREATE TABLE spot_comments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    spot_id INTEGER NOT NULL,
    comment VARCHAR(500) NOT NULL,
    user_id INTEGER NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    likes INTEGER DEFAULT 0,
    parent_id INTEGER,
    guid UUID NOT NULL DEFAULT gen_random_uuid(),

    CONSTRAINT uq_spot_comments_guid UNIQUE (guid),

    CONSTRAINT fk_spot_comments_spot
        FOREIGN KEY (spot_id) REFERENCES spots(id),

    CONSTRAINT fk_spot_comments_user
        FOREIGN KEY (user_id) REFERENCES users(id),

    CONSTRAINT fk_spot_comments_parent
        FOREIGN KEY (parent_id) REFERENCES spot_comments(id)
);

CREATE INDEX ix_spot_comments_parent_id
    ON spot_comments(parent_id);

CREATE INDEX ix_spot_comments_spot_id
    ON spot_comments(spot_id);

CREATE INDEX ix_spot_comments_user_id
    ON spot_comments(user_id);

CREATE TABLE spot_comment_likes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comment_id INTEGER NOT NULL,
    user_id INTEGER NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_comment_user
        UNIQUE (comment_id, user_id),

    CONSTRAINT fk_spot_comment_likes_comment
        FOREIGN KEY (comment_id) REFERENCES spot_comments(id),

    CONSTRAINT fk_spot_comment_likes_user
        FOREIGN KEY (user_id) REFERENCES users(id)
);